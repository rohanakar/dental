/**
 * Regenerate src/adapters/db/auth-schema.ts from the Better Auth config.
 * Run after changing auth plugins, then `pnpm db:generate` for a migration.
 *
 *   pnpm tsx scripts/gen-auth-schema.ts
 *
 * Uses the Drizzle schema generator that ships inside
 * @better-auth/drizzle-adapter (the same one the Better Auth CLI uses).
 */
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { authPlugins } from '../src/adapters/auth/plugins';

const betterAuthEntry = fileURLToPath(import.meta.resolve('better-auth'));
// .../node_modules/better-auth/dist/index.mjs -> .../node_modules
const nodeModules = join(dirname(betterAuthEntry), '..', '..');
const adapterDist = join(nodeModules, '@better-auth', 'drizzle-adapter', 'dist');
const generatorFile = readdirSync(adapterDist).find((f) => f.startsWith('generate-drizzle-schema-') && f.endsWith('.mjs'));
if (!generatorFile) throw new Error(`Drizzle schema generator not found in ${adapterDist}`);

const { generateDrizzleSchema } = (await import(pathToFileURL(join(adapterDist, generatorFile)).href)) as {
  generateDrizzleSchema: (args: {
    options: Record<string, unknown>;
    file: string;
    provider: 'pg';
    adapterConfig: Record<string, unknown>;
  }) => Promise<{ code: string }>;
};

const target = fileURLToPath(new URL('../src/adapters/db/auth-schema.ts', import.meta.url));
const { code } = await generateDrizzleSchema({
  options: { plugins: authPlugins(), emailAndPassword: { enabled: true } },
  file: target,
  provider: 'pg',
  adapterConfig: {},
});

// The generator emits drizzle v1 relation helpers; the adapter does not need
// relations (no experimental joins), so keep only the table definitions.
const relationsAt = code.search(/\nexport const \w*[Rr]elations\b/);
const tablesOnly = (relationsAt === -1 ? code : code.slice(0, relationsAt))
  .replace(/import \{[^}]*\} from "drizzle-orm";\n/, (line) => (/\bsql\b/.test(line) ? 'import { sql } from "drizzle-orm";\n' : ''))
  // Normalise the generator's mixed indentation (it expects prettier, which we don't ship).
  .replace(/^[ \t]+(?=\w+: )/gm, '  ')
  .replace(/^[ \t]+(?=\}(, \(table\) => \[|\);))/gm, '');

writeFileSync(
  target,
  `// GENERATED by scripts/gen-auth-schema.ts from the Better Auth config. Do not edit.\n${tablesOnly.trimEnd()}\n`,
);
console.log(`wrote ${target}`);
